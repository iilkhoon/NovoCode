// Yaradılan saytlar üçün başlanğıc şablonunu tək TS moduluna yığır.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve("src/lib/template/files");
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[path.relative(root, p).split(path.sep).join("/")] = readFileSync(p, "utf8");
  }
})(root);

writeFileSync(
  "src/lib/template/index.ts",
  `// AUTO-GENERATED by scripts/build-template.mjs — edit files in ./files instead.\n` +
    `export const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
);
console.log(`template: ${Object.keys(files).length} files`);
