// Yaradılan saytlar üçün başlanğıc şablonunu tək TS moduluna yığır.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve("src/lib/template/files");
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files[path.relative(root, p).split(path.sep).join("/")] = readFileSync(p, "utf8");
  }
})(root);

writeFileSync(
  "src/lib/template/index.ts",
  `// AUTO-GENERATED by scripts/build-template.mjs — edit files in ./files instead.\n` +
    `export const TEMPLATE_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};\n`
);
console.log(`template: ${Object.keys(files).length} files`);

// Ready-made site templates (only the files each one adds on top of the base).
const { siteIds, siteFiles } = await import("./templates-lib.mjs");
const sites = Object.fromEntries(siteIds().map((id) => [id, siteFiles(id).files]));
writeFileSync(
  "src/lib/templates/index.ts",
  `// AUTO-GENERATED by scripts/build-template.mjs — edit src/lib/templates/sites/<id> instead.\n` +
    `export const SITE_TEMPLATES: Record<string, Record<string, string>> = ${JSON.stringify(sites, null, 2)};\n`
);
console.log(`site templates: ${Object.keys(sites).join(", ")}`);
